#!/usr/bin/env python3
"""
Reference miner: point a WORKQUEUE item at two clean-room servers and get back
a short, attributed REFERENCE section you can paste under a spec.

    python3 ref_lookup.py hopper cooldown transfer      # explicit keywords
    python3 ref_lookup.py --item C1                      # pull keywords from WORKQUEUE.md
    python3 ref_lookup.py --item E2 --top 4

The two references live under refs/ and are BOTH permissively licensed:
  - Minestom  (Apache-2.0, Java)  tracks recent protocol but implements very
    little vanilla GAMEPLAY; good for packet/registry/structure shape.
  - Cuberite  (Apache-2.0, C++)   a full ~1.12-era gameplay server; good for
    block/mob/redstone ALGORITHM shape, wrong for any 26.x specifics.

Read the RULES header the tool prints on every run. The short version, encoded
so it travels with the output and nobody can plead ignorance:

  * SECONDARY only. The differential oracle (live vanilla RCON) and the wiki
    stay authoritative for MC 26.2. A reference tells you HOW someone shaped an
    algorithm, never WHAT the number is today.
  * Reference, do not copy. Pumpkin is MIT; verbatim Apache-2.0 would need an
    attribution and NOTICE trail this project does not want to carry. Take the
    structure and the control flow, write the Rust yourself.
  * Version caveat. Cuberite is ~1.12 and Minestom omits most gameplay, so a
    match here is a starting hypothesis, not a spec. Confirm against the oracle.

Hard refusal: Mojang's own decompiled sources are forbidden outright. If any
path under refs/ smells of decompiled Mojang code (a net/minecraft/... package
tree, mojmap names, Paper/Spigot server internals), this tool skips it and
says so rather than surfacing a single line of it.

stdlib only; no third-party deps. git CLI is used elsewhere in the rig to
clone the refs but is not needed here.
"""

import argparse
import math
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REFS = os.path.join(HERE, "refs")
WORKQUEUE = os.path.join(HERE, "WORKQUEUE.md")

# Per-repo: where the source lives, which extensions are real source, the
# version caveat that must ride along with any hit, and how to build a
# human-facing URL for a line range.
REPOS = {
    "Minestom": {
        "root": os.path.join(REFS, "Minestom", "src"),
        "exts": (".java", ".kt"),
        "caveat": "Apache-2.0 Java; recent protocol, minimal vanilla gameplay",
        "url": "https://github.com/Minestom/Minestom/blob/master/{rel}#L{a}-L{b}",
    },
    "Cuberite": {
        "root": os.path.join(REFS, "Cuberite", "src"),
        "exts": (".cpp", ".h", ".hpp"),
        "caveat": "Apache-2.0 C++; ~1.12-era behaviour, NOT 26.2",
        "url": "https://github.com/cuberite/Cuberite/blob/master/{rel}#L{a}-L{b}",
    },
}

# The definitive signatures of DECOMPILED Mojang game code or a derivative
# server's internals. We refuse to surface such a file at all. Kept precise on
# purpose: a clean-room project may legitimately have a directory literally
# named `mojang` (Minestom's auth-session helpers are `utils/mojang/`), which
# is Apache-2.0 first-party code, not decompiled Mojang. The real tells are the
# `net/minecraft/...` package tree, mojmap/MCP/yarn mapping output, and the
# Bukkit/Spigot/Paper server-internal packages.
MOJANG_PATH_MARKERS = re.compile(
    r"(^|/)(net/minecraft|mojmap|"
    r"org/spigotmc|org/bukkit/craftbukkit|io/papermc/paper)(/|$)", re.I)

# Autogenerated registries, palettes, and protocol id tables are DATA, not
# algorithms. They mention every entity/item/sound, so a keyword sprays hits
# across them and they drown the real logic. Heavily down-weighted, not hidden.
DATA_PATH_MARKERS = re.compile(
    r"autogenerated|/palettes?/|/registry/|/registries/|"
    r"keys\.(java|kt)$|events?\.(java|kt)$|palette_", re.I)

STOPWORDS = {
    "the", "and", "for", "with", "does", "not", "are", "was", "its", "has",
    "but", "that", "this", "from", "into", "per", "all", "any", "our", "out",
    "off", "via", "when", "then", "than", "over", "have", "only", "every",
    "never", "them", "they", "some", "each", "onto", "a", "an", "of", "to",
    "is", "it", "in", "on", "at", "or", "no", "vanilla", "pumpkin", "state",
    "confirmed", "suspected", "absent", "where", "what", "care", "wave",
    "already", "verify", "after", "merge", "though", "wired", "exists",
    "generic", "one", "set", "mod", "src", "there", "code", "impl",
}


# --------------------------------------------------------------------------
# Keyword extraction from a WORKQUEUE item.
# --------------------------------------------------------------------------
def load_item(item_id):
    """Return (name, keywords) for a WORKQUEUE item like C1, E2, J8.

    Keywords come from the item's short name plus its WHAT/VANILLA/WHERE lines,
    tokenised, lowercased, stripped of stopwords and pure numbers.
    """
    if not os.path.exists(WORKQUEUE):
        return None, []
    text = open(WORKQUEUE).read()
    m = re.search(rf"^###\s+{re.escape(item_id)}\b[ \t]*(.*)$", text, re.M)
    if not m:
        return None, []
    name = m.group(1).strip()
    start = m.end()
    nxt = re.search(r"^###\s|\n# ", text[start:], re.M)
    body = text[start: start + (nxt.start() if nxt else len(text) - start)]
    # Parentheticals in the name are almost always process notes ("already
    # PR'd as #2611, verify after merge"), not subject matter; drop them.
    clean_name = re.sub(r"\([^)]*\)", " ", name)
    # WHAT/VANILLA carry the subject nouns. WHERE is deliberately excluded: it
    # lists Pumpkin's OWN file paths (src, mod.rs, entity/passive/...), whose
    # tokens are noise against a differently-organised reference tree.
    picked = [clean_name]
    for line in body.splitlines():
        if re.match(r"\s*(WHAT|VANILLA)\b", line):
            picked.append(line)
    return name, _tokenise(" ".join(picked))


def _tokenise(s):
    words = re.findall(r"[A-Za-z_][A-Za-z0-9_]+", s)
    out = []
    for w in words:
        # split camelCase / snake_case identifiers into their parts too, since
        # a Rust name like is_raining_at should match Cuberite's IsRaining.
        parts = re.findall(r"[A-Z]+(?![a-z])|[A-Z][a-z]+|[a-z]+|[0-9]+", w)
        for p in [w] + parts:
            p = p.lower()
            if len(p) >= 3 and p not in STOPWORDS and not p.isdigit():
                out.append(p)
    seen, uniq = set(), []
    for w in out:
        if w not in seen:
            seen.add(w)
            uniq.append(w)
    return uniq[:12]


# --------------------------------------------------------------------------
# Search.
# --------------------------------------------------------------------------
def _is_mojang(rel_path):
    return bool(MOJANG_PATH_MARKERS.search(rel_path.replace(os.sep, "/")))


def _iter_sources(root, exts):
    for dirpath, _dirs, files in os.walk(root):
        for fn in files:
            if fn.endswith(exts):
                yield os.path.join(dirpath, fn)


def search_repo(name, cfg, keywords, top):
    """Score every source file by keyword hits; return the top matches with
    line ranges and a one-line 'approach' hint per file.

    Scoring is IDF-weighted: a keyword that appears in almost every file (say
    "entity") carries far less weight than a rare, specific one ("villager",
    "tripwire", "cooldown"). Without this, generic terms dominate and the top
    hit is whichever file happens to be longest. Autogenerated data tables are
    additionally down-weighted, because they name every id in the game and so
    match any keyword by accident.
    """
    root = cfg["root"]
    if not os.path.isdir(root):
        return {"error": f"{root} missing; clone the reference first"}, []
    # Word-boundary match, case-insensitive. This does two good things at once:
    # short generic tokens stop matching inside bigger words ("can" no longer
    # hits "Cancellable"), while a full compound token like "canavoidtraps"
    # still matches the identifier "canAvoidTraps" as a whole word.
    pats = list(zip(keywords,
                    (re.compile(rf"\b{re.escape(k)}\b", re.I) for k in keywords)))
    refused = 0

    # Pass 1: gather per-file hits and per-keyword document frequency.
    files = []          # (rel, path, hits{line:count}, kw_seen, is_data)
    df = {k: 0 for k in keywords}
    for path in _iter_sources(root, cfg["exts"]):
        rel = os.path.relpath(path, os.path.join(REFS, name))
        if _is_mojang(rel):
            refused += 1
            continue
        try:
            lines = open(path, errors="replace").read().splitlines()
        except OSError:
            continue
        hits, kw_seen = {}, set()
        for i, line in enumerate(lines):
            c = 0
            for k, pat in pats:
                if pat.search(line):
                    c += 1
                    kw_seen.add(k)
            if c:
                hits[i] = c
        if not hits:
            continue
        for k in kw_seen:
            df[k] += 1
        files.append((rel, path, hits, kw_seen, bool(DATA_PATH_MARKERS.search(rel)), lines))

    # Pass 2: score with IDF weights. A keyword present in more than ~35% of
    # the matched files is effectively a per-corpus stopword ("entity" in a
    # server codebase); give it a floor weight so it cannot drive ranking but
    # still breaks ties. Rare, specific terms keep their full IDF.
    n = max(1, len(files))
    weight = {}
    for k in keywords:
        if not df[k]:
            continue
        weight[k] = 0.05 if df[k] > 0.35 * n else math.log(1 + n / df[k])
    scored = []
    for rel, path, hits, kw_seen, is_data, lines in files:
        kw_weights = [weight.get(k, 0.0) for k in kw_seen]
        base = sum(kw_weights)
        # Boost the RAREST matched term hard. Otherwise a big core file that
        # brushes many common words ("entity", "world", "can") outranks the one
        # small file that actually owns the specific subject ("tripwire"). The
        # most-specific keyword present is the strongest relevance signal.
        if kw_weights:
            base += 2.0 * max(kw_weights)
        # a small bonus for repeated hits, capped so a data table cannot win on
        # sheer volume
        base += min(sum(hits.values()), 20) * 0.02
        fname = os.path.basename(path).lower()
        if any(pat.search(fname) for _, pat in pats):
            base += 1.5  # a filename match is worth a lot
        if is_data:
            base *= 0.15  # data tables: kept as a fallback, never a headline
        scored.append((round(base, 3), len(kw_seen), rel, path, hits, lines))
    scored.sort(key=lambda t: t[0], reverse=True)
    return {"refused": refused, "root": root}, scored[:top]


def _ranges(line_nos, gap=8):
    """Cluster matching line numbers into human line ranges (1-based)."""
    nos = sorted(line_nos)
    out, start, prev = [], nos[0], nos[0]
    for n in nos[1:]:
        if n - prev <= gap:
            prev = n
        else:
            out.append((start + 1, prev + 1))
            start = prev = n
    out.append((start + 1, prev + 1))
    return out


_SIG = re.compile(
    r"\b(fn|def|void|public|private|protected|static|bool|int|class|struct|"
    r"cChunk|cWorld|cPlayer|impl|pub)\b")


def _approach(lines, hit_line):
    """A one-line 'what this code is doing' hint: the nearest declaration or
    comment at or above the strongest matching line, plus that line."""
    decl = ""
    for j in range(hit_line, max(-1, hit_line - 40), -1):
        s = lines[j].strip()
        if s.startswith(("//", "#", "/*", "*")) and len(s) > 4 and not decl:
            decl = s.lstrip("/*# ").strip()
        if _SIG.search(lines[j]) and "(" in lines[j]:
            decl = lines[j].strip()
            break
    body = lines[hit_line].strip()
    return decl[:100], body[:110]


def emit(keywords, per_repo, out=sys.stdout):
    p = out.write
    p("REFERENCE  (SECONDARY - oracle + wiki remain authoritative for 26.2)\n")
    p("  Reference, do not copy: take the algorithm and control flow, write the\n")
    p("  Rust yourself. Pumpkin is MIT; verbatim Apache-2.0 would need an\n")
    p("  attribution/NOTICE trail this project does not carry. Cuberite is\n")
    p("  ~1.12 and Minestom omits most gameplay, so confirm every specific\n")
    p("  (numbers, timings, block ids) against the differential oracle.\n")
    p(f"  keywords: {', '.join(keywords)}\n")
    any_hit = False
    for name, (meta, hits) in per_repo.items():
        p(f"\n  == {name} ({REPOS[name]['caveat']}) ==\n")
        if meta.get("error"):
            p(f"     ! {meta['error']}\n")
            continue
        if meta.get("refused"):
            p(f"     (skipped {meta['refused']} path(s) that looked like "
              f"decompiled Mojang/derivative code)\n")
        if not hits:
            p("     no relevant source found for these keywords\n")
            continue
        for score, nkw, rel, _path, hitmap, lines in hits:
            any_hit = True
            rngs = _ranges(list(hitmap))
            rng_txt = ", ".join(f"{a}-{b}" if a != b else str(a) for a, b in rngs[:4])
            best = max(hitmap, key=lambda k: hitmap[k])
            decl, body = _approach(lines, best)
            url = REPOS[name]["url"].format(rel=rel.replace(os.sep, "/"),
                                            a=rngs[0][0], b=rngs[0][1])
            p(f"     - {rel}  (L{rng_txt}; {nkw} kw, score {score})\n")
            if decl:
                p(f"         approach: {decl}\n")
            p(f"         match:    {body}\n")
            p(f"         url:      {url}\n")
    if not any_hit:
        p("\n  No usable reference. Rely on the oracle and the wiki.\n")


# --------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description="mine clean-room refs for a WORKQUEUE item")
    ap.add_argument("keywords", nargs="*", help="keywords to search (or use --item)")
    ap.add_argument("--item", help="WORKQUEUE item id (e.g. C1) to derive keywords from")
    ap.add_argument("--top", type=int, default=3, help="max files per repo (default 3)")
    a = ap.parse_args()

    keywords = [k.lower() for k in a.keywords]
    if a.item:
        name, kw = load_item(a.item)
        if name is None:
            print(f"WORKQUEUE item {a.item!r} not found in {WORKQUEUE}")
            return 2
        print(f"# item {a.item}: {name}")
        # explicit keywords, if any, refine the item's auto-extracted set
        keywords = keywords or kw
    if not keywords:
        print("no keywords; pass some, or --item <ID>")
        return 2

    if not os.path.isdir(REFS):
        print(f"refs/ not present at {REFS}. Clone the references first:")
        print("  git clone --depth 1 https://github.com/Minestom/Minestom refs/Minestom")
        print("  git clone --depth 1 https://github.com/cuberite/Cuberite refs/Cuberite")
        return 1

    per_repo = {}
    for name, cfg in REPOS.items():
        per_repo[name] = search_repo(name, cfg, keywords, a.top)
    emit(keywords, per_repo)
    return 0


if __name__ == "__main__":
    sys.exit(main())
